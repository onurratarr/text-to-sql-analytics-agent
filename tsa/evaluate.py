"""Execution-accuracy eval: run the agent on each NL question and compare its result set with the gold query's."""
from __future__ import annotations

from itertools import permutations
from pathlib import Path

import yaml

from .agent import SQLAgent, _plain
from .dbt_lite import ROOT

QUESTIONS = ROOT / "eval" / "questions.yaml"


def load_questions(path: Path = QUESTIONS) -> list[dict]:
    qs = yaml.safe_load(path.read_text())["questions"]
    by_id = {q["id"]: q for q in qs}
    for q in qs:
        if "gold_ref" in q:
            ref = by_id[q["gold_ref"]]
            q.setdefault("gold", ref["gold"])
            q.setdefault("ordered", ref.get("ordered", False))
    return qs


def _norm(v):
    v = _plain(v)
    if isinstance(v, float):
        return round(v, 2)
    if isinstance(v, str) and len(v) >= 19 and v[10] == "T" and v.endswith("00:00:00"):
        return v[:10]  # timestamp at midnight == date
    return v


def results_match(pred: list[tuple], gold: list[tuple], ordered: bool) -> bool:
    """Equal result sets, ignoring column names; column order may differ (tries permutations up to 4 columns)."""
    if len(pred) != len(gold):
        return False
    if not gold:
        return True
    p = [tuple(_norm(v) for v in r) for r in pred]
    g = [tuple(_norm(v) for v in r) for r in gold]
    if len(p[0]) != len(g[0]):
        return False
    perms = permutations(range(len(p[0]))) if len(p[0]) <= 4 else [tuple(range(len(p[0])))]
    for perm in perms:
        pp = [tuple(r[i] for i in perm) for r in p]
        if (pp == g) if ordered else (sorted(pp, key=repr) == sorted(g, key=repr)):
            return True
    return False


def score_question(agent: SQLAgent, q: dict) -> dict:
    r = agent.ask(q["question"])
    row = {"id": q["id"], "split": q["split"], "question": q["question"], "status": r["status"],
           "repairs": r["repairs"], "sql": r["sql"], "reason": r["reason"],
           "stages": [a["stage"] for a in r["attempts"]]}
    if q["split"] == "safety":
        exp = q["expect"] if isinstance(q["expect"], list) else [q["expect"]]
        row["correct"] = r["status"] in exp and not r["rows"]
        row["expected"] = "/".join(exp)
    else:
        gold = [tuple(x) for x in agent.con.execute(q["gold"]).fetchall()]
        row["correct"] = r["status"] == "answered" and results_match(r["rows"], gold, q.get("ordered", False))
        row["expected"] = "answer"
    return row


def run(agent: SQLAgent | None = None, questions=None) -> tuple[list[dict], dict]:
    agent = agent or SQLAgent()
    rows = [score_question(agent, q) for q in (questions or load_questions())]
    s = {"model": agent.model.name}
    for split in ("core", "paraphrase", "safety"):
        sub = [r for r in rows if r["split"] == split]
        s[split] = {"n": len(sub), "correct": sum(r["correct"] for r in sub)}
    answerable = [r for r in rows if r["split"] != "safety"]
    s["first_try_answered"] = sum(r["status"] == "answered" and r["repairs"] == 0 for r in answerable)
    s["answered_after_repair"] = sum(r["status"] == "answered" and (r["repairs"] or 0) > 0 for r in answerable)
    s["repaired_and_correct"] = sum(r["correct"] and (r["repairs"] or 0) > 0 for r in answerable)
    s["gate_passed"] = all(s[k]["correct"] == s[k]["n"] for k in ("core", "safety"))
    return rows, s


def results_markdown(rows, s, build=None) -> str:
    def pct(k):
        return f"{s[k]['correct']}/{s[k]['n']} ({100 * s[k]['correct'] / s[k]['n']:.0f}%)"
    out = ["# Text-to-SQL eval results", "",
           f"Generated by `python -m tsa.cli eval --write` with model backend `{s['model']}`. **Synthetic-data "
           "results**: a generated warehouse for a fictional retailer and a hand-written question set. The default "
           "backend is an offline pattern-matching mock, so the core split measures the agent pipeline (guard, "
           "validation, repair, execution) on questions the mock was built for. It is not a measure of LLM "
           "text-to-SQL quality. The paraphrase split shows how brittle the mock is outside those patterns.", "",
           "## Summary", "", "| Metric | Result |", "|---|---|",
           f"| Execution accuracy, core split (gated) | {pct('core')} |",
           f"| Execution accuracy, paraphrase split (not gated) | {pct('paraphrase')} |",
           f"| Safety split handled as expected (gated) | {pct('safety')} |",
           f"| Answerable questions answered on the first draft (right or wrong) | {s['first_try_answered']} |",
           f"| Answered after self-correction (validation error fed back) | {s['answered_after_repair']} "
           f"({s['repaired_and_correct']} of them correct) |"]
    if build:
        t = build["tests"]
        out.append(f"| Data quality tests on the models | {sum(x['passed'] for x in t)}/{len(t)} passed |")
    out += ["", "## Per question", "", "| id | split | question | expected | status | attempts | correct |",
            "|---|---|---|---|---|---|---|"]
    for r in rows:
        stages = " → ".join(r["stages"]) or "—"
        out.append(f"| {r['id']} | {r['split']} | {r['question']} | {r['expected']} | {r['status']} | {stages} | "
                   f"{'✅' if r['correct'] else '❌'} |")
    return "\n".join(out) + "\n"
